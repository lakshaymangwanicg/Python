num=float(input("Enter a Number: "))
if num<0:
    print("Output: Negative Number")
elif 0<=num<=10:
    print("Output: Number is between 0 and 10")
elif 11<=num<=50:
    print("Output: Number is between 11 and 50")
elif 51<=num<=100:
    print("Output: Number is between 51 and 100")
else:
    print("Output: Number is greater than 100")        




